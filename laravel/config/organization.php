<?php

return [

    /*
    |--------------------------------------------------------------------------
    | 許容メールアドレスドメイン
    |--------------------------------------------------------------------------
    |
    | 社内アカウント（ログインID）として許可するメールアドレスのドメインを
    | カンマ区切りで指定する。複数ドメイン対応。
    | 例：ALLOWED_EMAIL_DOMAINS=nexus.example.com,nexus.co.jp
    |
    | 組織全体のアイデンティティ方針であり、マスタ管理のユーザー登録・編集、
    | app:create-admin コマンド、（今後の）ログイン/認証など機能横断で参照する。
    | このため特定機能の config ではなく組織方針の config として保持する。
    |
    | 未設定（空）の場合はドメイン制限を掛けず、メール形式チェックのみ行う
    | （許容ドメインが確定するまでの暫定運用・TBD#3）。ハードコードは避け、
    | 環境変数で柔軟に変更できるようにしている。
    |
    */

    'allowed_email_domains' => array_values(array_filter(array_map(
        'trim',
        explode(',', (string) env('ALLOWED_EMAIL_DOMAINS', '')),
    ))),

];
